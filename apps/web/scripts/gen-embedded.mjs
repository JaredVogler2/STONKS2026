#!/usr/bin/env node
// Embeds SQL migrations into a TS module so serverless bundles never depend on runtime file paths.
// `--check` fails when the committed module is stale (run in CI).
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "../../..");
const migDir = join(repo, "supabase", "migrations");
const out = resolve(here, "../src/server/db/migrations.generated.ts");

const files = readdirSync(migDir).filter((f) => /^\d{14}_[a-z0-9_]+\.sql$/.test(f)).sort();
const entries = files.map((f) => {
  const sql = readFileSync(join(migDir, f), "utf8");
  return {
    version: f.slice(0, 14),
    name: f.slice(15, -4),
    checksum: createHash("sha256").update(sql).digest("hex"),
    sql,
  };
});
const body =
  "/* AUTO-GENERATED by apps/web/scripts/gen-embedded.mjs from supabase/migrations. DO NOT EDIT. */\n" +
  "export interface EmbeddedMigration { version: string; name: string; checksum: string; sql: string }\n" +
  `export const MIGRATIONS: EmbeddedMigration[] = ${JSON.stringify(entries, null, 2)};\n`;

if (process.argv.includes("--check")) {
  if (!existsSync(out) || readFileSync(out, "utf8") !== body) {
    console.error("migrations.generated.ts is stale: run `pnpm --filter @apex/web gen`");
    process.exit(1);
  }
  console.log(`embedded migrations OK (${entries.length})`);
} else {
  writeFileSync(out, body);
  console.log(`wrote ${out} (${entries.length} migrations)`);
}
