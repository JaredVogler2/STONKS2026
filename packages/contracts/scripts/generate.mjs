#!/usr/bin/env node
// Generates TypeScript types and Pydantic models from the JSON Schemas in ../schemas.
// The JSON Schemas are the single source of truth. `--check` fails if committed output drifts.
import { compile } from "json-schema-to-typescript";
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, readdirSync, writeFileSync, rmSync, mkdirSync, copyFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(here, "..");
const repoRoot = resolve(pkgRoot, "../..");
const schemaDir = join(pkgRoot, "schemas");
const tsOut = join(pkgRoot, "src", "generated.ts");
const pyPkg = join(repoRoot, "apps", "pi-worker", "src", "apex_worker", "contracts");
const pyOut = join(pyPkg, "models.py");
const pySchemaCopy = join(pyPkg, "schemas");
const check = process.argv.includes("--check");

const schemaFiles = readdirSync(schemaDir).filter((f) => f.endsWith(".schema.json")).sort();
const topLevel = schemaFiles.filter((f) => f !== "common.schema.json");

function loadSchema(file) {
  return JSON.parse(readFileSync(join(schemaDir, file), "utf8"));
}

// Build one bundle so every shared definition is emitted exactly once.
const bundle = {
  $schema: "https://json-schema.org/draft/2020-12/schema",
  title: "ApexContractBundle",
  type: "object",
  additionalProperties: false,
  properties: Object.fromEntries(topLevel.map((f) => [loadSchema(f).title, { $ref: `./${f}` }])),
};

const banner = "/* AUTO-GENERATED by packages/contracts/scripts/generate.mjs from JSON Schema. DO NOT EDIT. */";

async function generateTs() {
  const ts = await compile(bundle, "ApexContractBundle", {
    cwd: schemaDir,
    bannerComment: banner,
    additionalProperties: false,
    unreachableDefinitions: false,
    style: { singleQuote: false, semi: true, printWidth: 110 },
  });
  return ts;
}

function generatePy() {
  const work = mkdtempSync(join(tmpdir(), "apex-contracts-"));
  try {
    for (const f of schemaFiles) copyFileSync(join(schemaDir, f), join(work, f));
    const bundlePath = join(work, "_bundle.schema.json");
    writeFileSync(bundlePath, JSON.stringify(bundle, null, 2));
    const outPath = join(work, "models.py");
    const pyproject = join(repoRoot, "apps", "pi-worker");
    execFileSync(
      "uv",
      [
        "run", "--project", pyproject, "--quiet", "datamodel-codegen",
        "--input", bundlePath,
        "--input-file-type", "jsonschema",
        "--output", outPath,
        "--output-model-type", "pydantic_v2.BaseModel",
        "--target-python-version", "3.11",
        "--use-standard-collections",
        "--use-union-operator",
        "--use-title-as-name",
        "--use-schema-description",
        "--field-constraints",
        "--enum-field-as-literal", "all",
        "--disable-timestamp",
        "--extra-fields", "forbid",
        "--formatters", "ruff-format",
        "--custom-file-header", "# AUTO-GENERATED by packages/contracts/scripts/generate.mjs from JSON Schema. DO NOT EDIT.",
      ],
      { stdio: ["ignore", "pipe", "inherit"], env: { ...process.env, UV_NATIVE_TLS: undefined } },
    );
    return readFileSync(outPath, "utf8");
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

const ts = await generateTs();
const py = generatePy();

if (check) {
  let drift = [];
  if (!existsSync(tsOut) || readFileSync(tsOut, "utf8") !== ts) drift.push(tsOut);
  if (!existsSync(pyOut) || readFileSync(pyOut, "utf8") !== py) drift.push(pyOut);
  for (const f of schemaFiles) {
    const copy = join(pySchemaCopy, f);
    if (!existsSync(copy) || readFileSync(copy, "utf8") !== readFileSync(join(schemaDir, f), "utf8")) drift.push(copy);
  }
  if (drift.length) {
    console.error("Generated contracts are out of date. Run `pnpm contracts:generate`.\n" + drift.join("\n"));
    process.exit(1);
  }
  console.log(`contracts OK (${schemaFiles.length} schemas)`);
} else {
  writeFileSync(tsOut, ts);
  mkdirSync(pySchemaCopy, { recursive: true });
  writeFileSync(pyOut, py);
  for (const f of schemaFiles) copyFileSync(join(schemaDir, f), join(pySchemaCopy, f));
  console.log(`generated ${tsOut}\ngenerated ${pyOut}\ncopied ${schemaFiles.length} schemas`);
}
